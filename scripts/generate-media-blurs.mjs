import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const inputs = ["lib/caseStudies.ts", "lib/about.ts"];
const urls = new Set();
for (const input of inputs) {
  const source = readFileSync(input, "utf8");
  for (const match of source.matchAll(/"(\/[^"?]+\.(?:avif|jpe?g|png|webp))(?:\?[^" ]*)?"/gi)) {
    if (existsSync(path.join("public", match[1].slice(1)))) urls.add(match[1]);
  }
}

const entries = [];
const sizes = [];
for (const url of [...urls].sort()) {
  const input = path.join("public", url.slice(1));
  const result = spawnSync("ffmpeg", [
    "-v", "error", "-i", input,
    "-vf", "scale=32:-2,boxblur=2:1", "-frames:v", "1",
    "-q:v", "12", "-f", "image2pipe", "-vcodec", "mjpeg", "-",
  ], { encoding: "buffer", maxBuffer: 1024 * 1024 });
  if (result.status !== 0) throw new Error(`Could not render blur for ${url}`);
  entries.push(`  ${JSON.stringify(url)}: "data:image/jpeg;base64,${result.stdout.toString("base64")}",`);
  sizes.push(`  ${JSON.stringify(url)}: ${statSync(input).size},`);
}

writeFileSync(
  "lib/mediaBlurData.generated.ts",
  [
    "// Generated by scripts/generate-media-blurs.mjs. Do not edit by hand.",
    "export const MEDIA_BLURS: Record<string, string> = {", ...entries, "};",
    "export const MEDIA_IMAGE_BYTES: Record<string, number> = {", ...sizes, "};", "",
  ].join("\n"),
);
console.log(`Generated ${entries.length} lightweight media previews`);
